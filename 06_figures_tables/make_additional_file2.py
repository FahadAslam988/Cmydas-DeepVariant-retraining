"""Additional file 2 (Excel): full results of Paper 2, generated from the source tables in 03_tables/ (no hand-typed numbers)."""
import csv, os
from openpyxl import Workbook
from openpyxl.styles import Font, Alignment
H = os.path.dirname(os.path.abspath(__file__)); P2 = os.path.join(H, '..', '..'); T = os.path.join(P2, '03_tables')
def tsv(f): return list(csv.DictReader(open(os.path.join(T, f)), delimiter='\t'))
NAME = {'RetrainedDV_sim': 'Retrained DeepVariant (depth-matched)', 'RetrainedDV_sim_70xmodel': 'Retrained DeepVariant (70x model)',
        'RetrainedDV2': 'Retrained DeepVariant (70x model)', 'StockDV': 'Default DeepVariant', 'BCF': 'BCFtools', 'Freebayes': 'FreeBayes',
        'Gatk': 'GATK', 'Varscan': 'VarScan'}
def grp(g):
    p = g.split('_')
    if p[0] == 'sim': return ('Simulated test contigs', p[1], p[2], '', '')
    return ('Real reads', {'normal': 'CH-NORMS1', 'abnormal': 'Ab-NormS2'}[p[1]], p[-1], p[2].replace('k', ''), p[3])
def num(v):
    try: return int(v) if v.isdigit() else float(v)
    except Exception: return v
wb = Workbook(); wb.remove(wb.active)
def sheet(name, head, rows):
    ws = wb.create_sheet(name); ws.append(head)
    for c in ws[1]: c.font = Font(bold=True); c.alignment = Alignment(wrap_text=True)
    for r in rows: ws.append([num(str(x)) if not isinstance(x, (int, float)) else x for x in r])
    for col in ws.columns: ws.column_dimensions[col[0].column_letter].width = 18
    ws.freeze_panes = 'A2'
ci = [r for r in tsv('Bootstrap_bootstrap_F1_CI.tsv')]
# S1 accuracy with CIs (+ ranks by F1, simulation only)
rk1 = {(x['Group'], x['Caller']): float(x['Share_rank1']) for x in tsv('Bootstrap_bootstrap_rank_stability.tsv')}
rows = []
for g in dict.fromkeys(r['Group'] for r in ci):
    rs = [r for r in ci if r['Group'] == g]
    pool = [r for r in rs if not (g.startswith('sim') and r['Caller'] == 'RetrainedDV_sim_70xmodel')]
    order = sorted(pool, key=lambda r: -float(r['F1']))
    for r in rs:
        rank = 1 + sum(float(o['F1']) > float(r['F1']) for o in pool) if r in pool else ''  # ties share a rank
        rows.append(list(grp(g)) + [NAME[r['Caller']], r['Precision'], r['P_lo'], r['P_hi'], r['Recall'], r['R_lo'], r['R_hi'], r['F1'], r['F1_lo'], r['F1_hi'],
                                    r['TP'], r['FN'], r['FP'], rank, rk1.get((g, r['Caller']), '') if g.startswith('sim') else ''])
sheet('S1_accuracy_CI', ['Data', 'Depth or genome', 'Variant type', 'LOO k', 'Region', 'Caller', 'Precision', 'Precision CI low', 'Precision CI high',
      'Recall', 'Recall CI low', 'Recall CI high', 'F1', 'F1 CI low', 'F1 CI high', 'TP', 'FN', 'FP', 'Rank by F1 (simulation; 70x model at lower depth not ranked)',
      'Share of bootstrap replicates ranked first'], rows)
df = [r for r in tsv('Bootstrap_bootstrap_pairwise_F1_diff.tsv')]
sheet('S2_F1_differences', ['Data', 'Depth or genome', 'Variant type', 'LOO k', 'Region', 'Model', 'Compared with', 'F1 difference (model minus compared)',
      'CI low', 'CI high', 'Share of replicates model better', 'CI excludes zero'],
      [list(grp(r['Group'])) + [NAME[r['CallerA']], NAME[r['CallerB']], r['F1_A_minus_B'], r['lo'], r['hi'], r['Share_A_better'], r['CI_excludes_0']] for r in df])
rows = []
for n in ('CH-NORMS1', 'Ab-NormS2'):
    for r in tsv(f'RealReads_{n}_LOO_WG_F1_rank_all_callers.tsv'):
        rows.append([n, r['k'], r['Caller'], r['TP'], r['FP'], r['FN'], r['Precision'], r['Recall'], r['F1'], r['Rank_of_6'], r['Rank_of_5_DV2_replaces_default'], r['Rank_of_5_original']])
sheet('S3_real_reads_all_callers', ['Genome', 'LOO k', 'Caller', 'TP', 'FP', 'FN', 'Precision', 'Recall', 'F1', 'Rank of 6',
      'Rank of 5 (retrained replaces default)', 'Rank of 5 (default)'], rows)
rows = []
for n in ('CH-NORMS1', 'Ab-NormS2'):
    for r in tsv(f'RealReads_{n}_sanity_TiTv_HetHom_support.tsv'):
        rows.append([n, r['Region'], NAME[r['Model']], r['SNPs'], r['TiTv'], r['Het'], r['HomAlt'], r['Het/Hom'], r['Supported_by_other_callers_%'], r['Private_SNPs']])
sheet('S4_real_reads_checks', ['Genome', 'Region', 'Model', 'SNPs', 'Ti/Tv', 'Heterozygous', 'Homozygous alternative', 'Het/Hom ratio',
      'Reported by at least one other caller (%)', 'Reported by no other caller'], rows)
cur = list(csv.DictReader(open(os.path.join(P2, '09_analysis_scripts_logs_results/05_coverage_per_depth_retraining/09_training_curves_and_checkpoint_selection/training_curves_all_depths.tsv')), delimiter='\t'))
sheet('S5_training_curves', ['Model depth', 'Set', 'Training step', 'Epoch', 'Weighted F1', 'Loss'],
      [[r['depth'], r['split'], r['step'], r['epoch'], r['f1_weighted'], r['loss']] for r in cur if not (r['split'] == 'validation' and r['step'] == '0')])
ws = wb.create_sheet('README', 0)
for line in ['Additional file 2. Full results of the retraining study (green sea turtle, DeepVariant v1.9.0).',
             'All values were generated by script from the source result files; see the Methods for definitions.',
             'S1_accuracy_CI: precision, recall and F1 with 95% CIs (paired block bootstrap, 1-Mb blocks, 1000 replicates, seed 20261001) for every caller and model.',
             '   Simulated test contigs (52.0 Mb, genotype-level scoring) at 70x, 30x, 15x, 10x; real reads (SNPs, allele-level scoring) against leave-one-out (LOO) truth sets.',
             'S2_F1_differences: F1 difference between each retrained model and every other call set, with 95% CI.',
             'S3_real_reads_all_callers: whole-genome SNP accuracy and rank of all callers on real reads; each caller scored against its own LOO truth set (built from the other four callers).',
             'S4_real_reads_checks: number of SNPs, Ti/Tv, heterozygous/homozygous ratio and support by other callers for default and retrained DeepVariant.',
             'S5_training_curves: weighted F1 and loss on training and validation examples during fine-tuning (selected checkpoints in Additional file 1).',
             'Region: WG = whole genome; TEST = held-out test contigs; UNUSED = contigs not part of the simulation (never used in training, validation or testing).',
             'TP, true positives; FP, false positives; FN, false negatives; CI, confidence interval; LOO k, minimum number of the other four callers reporting a SNP.']:
    ws.append([line])
ws.column_dimensions['A'].width = 160
out = os.path.join(P2, '04_additional_files', 'Additional_file_2.xlsx'); wb.save(out); print('saved', out)
